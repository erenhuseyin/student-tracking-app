with kok as (
  select id from public.kurum where marka_kodu = 'varsayilan'
)
insert into public.kademe (kurum_id, ad, sira)
select distinct kok.id, t.kademe, t.kademe_sira from kok, tohum_konu t
on conflict (kurum_id, ad) do nothing;

with kok as (
  select id from public.kurum where marka_kodu = 'varsayilan'
)
insert into public.kademe_dersi (kurum_id, kademe_id, ad, sira)
select distinct kok.id, k.id, t.ders, t.ders_sira
from kok, tohum_konu t
join public.kademe k on k.ad = t.kademe
where k.kurum_id = kok.id
on conflict (kademe_id, ad) do nothing;

with kok as (
  select id from public.kurum where marka_kodu = 'varsayilan'
)
insert into public.ders_konusu (kurum_id, ders_id, ad, sira)
select kok.id, d.id, t.ad, t.sira
from kok, tohum_konu t
join public.kademe k on k.ad = t.kademe
join public.kademe_dersi d on d.kademe_id = k.id and d.ad = t.ders
where k.kurum_id = kok.id
  and not exists (
    select 1 from public.ders_konusu c
    where c.ders_id = d.id and lower(btrim(c.ad)) = lower(btrim(t.ad))
  )
order by t.kademe_sira, t.ders_sira, t.sira;

drop table tohum_konu;
